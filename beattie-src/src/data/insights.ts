export type Tone = 'gold' | 'ok' | 'soft' | 'warn' | 'danger' | 'deep';

export interface BandInsight {
  min: number;
  max: number;
  lamp: string;
  tone: Tone;
  headline: string;
  means: string[];
  actions: string[];
}

export interface TestReading {
  id: string;
  blurb: string;
  theme: string;
  bands: BandInsight[];
}

const LEVEL = {
  check: { min: 220, max: 230, lamp: '再核对', tone: 'gold' as const },
  steady: { min: 190, max: 219, lamp: '绿灯', tone: 'ok' as const },
  growing: { min: 160, max: 189, lamp: '在路上', tone: 'soft' as const },
  yellow: { min: 130, max: 159, lamp: '黄灯', tone: 'warn' as const },
  red: { min: 100, max: 129, lamp: '红灯', tone: 'danger' as const },
  deep: { min: 0, max: 99, lamp: '先照顾自己', tone: 'deep' as const },
};

function band(
  level: keyof typeof LEVEL,
  headline: string,
  means: string[],
  actions: string[],
): BandInsight {
  return { ...LEVEL[level], headline, means, actions };
}

