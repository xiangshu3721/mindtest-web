for (const reading of readings) {
  if (reading.bands.length !== 6) {
    throw new Error(`insight bands for ${reading.id}`);
  }
  for (const item of reading.bands) {
    if (item.means.length < 3 || item.means.length > 6) {
      throw new Error(`means length for ${reading.id} ${item.min}`);
    }
    if (item.actions.length < 3 || item.actions.length > 5) {
      throw new Error(`actions length for ${reading.id} ${item.min}`);
    }
  }
}

export function readingFor(testId: string): TestReading | undefined {
  return readings.find((r) => r.id === testId);
}

export function insightFor(testId: string, total: number): BandInsight | undefined {
  const reading = readingFor(testId);
  if (!reading) return undefined;
  return reading.bands.find((b) => total >= b.min && total <= b.max);
}
